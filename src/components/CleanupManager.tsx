export function formatRelativeTime(isoString?: string): string {
  if (!isoString) return "Never cleared";
  const date = new Date(isoString);
  if (isNaN(date.getTime())) return "Never cleared";

  const now = new Date();
  const diffMs = now.getTime() - date.getTime();
  if (diffMs < 0) return "Just now";

  const diffMinutes = Math.floor(diffMs / (1000 * 60));
  if (diffMinutes < 1) return "Just now";
  if (diffMinutes < 60) return `${diffMinutes} min${diffMinutes > 1 ? 's' : ''} ago`;

  const diffHours = Math.floor(diffMinutes / 60);
  if (diffHours < 24) return `${diffHours} hour${diffHours > 1 ? 's' : ''} ago`;

  const diffDays = Math.floor(diffHours / 24);
  if (diffDays === 1) return "Yesterday";
  if (diffDays < 30) return `${diffDays} days ago`;

  const diffMonths = Math.floor(diffDays / 30);
  return `${diffMonths} month${diffMonths > 1 ? 's' : ''} ago`;
}

export function getFolderScheduleStatus(lastClearedIso?: string, recommendedIntervalDays: number = 7) {
  if (!lastClearedIso) {
    return {
      label: "Never Cleared",
      badgeClass: "bg-slate-500/15 text-slate-400 border-slate-500/30",
      isOverdue: false,
      isDueSoon: true
    };
  }

  const date = new Date(lastClearedIso);
  const diffDays = (Date.now() - date.getTime()) / (1000 * 3600 * 24);

  if (diffDays > recommendedIntervalDays) {
    return {
      label: "Overdue Maintenance",
      badgeClass: "bg-red-500/15 text-red-400 border-red-500/30 animate-pulse",
      isOverdue: true,
      isDueSoon: false
    };
  }

  if (diffDays >= recommendedIntervalDays - 2) {
    return {
      label: "Due Soon",
      badgeClass: "bg-amber-500/15 text-amber-400 border-amber-500/30",
      isOverdue: false,
      isDueSoon: true
    };
  }

  return {
    label: "Recently Cleared",
    badgeClass: "bg-emerald-500/15 text-emerald-400 border-emerald-500/30",
    isOverdue: false,
    isDueSoon: false
  };
}

